// ── Lecture du fichier ──────────────────────────────────────────────────────────────────────

function verifierMotif(motif) {
  if (/^https?:\/\//i.test(motif)) {
    if (!/^https:\/\//i.test(motif)) return "une URL absolue doit commencer par https";
    const hote = motif.slice(8).split("/")[0];
    if (/:\d+$/.test(hote)) return "port précisé dans l'URL, non pris en charge";
  } else if (!motif.startsWith("/")) {
    return "un motif commence par / (chemin) ou par https:// (URL absolue)";
  }
  if ((motif.match(/\*/g) || []).length > 1) return "plus d'un astérisque, alors qu'un seul est admis par URL";
  return null;
}

export function lireHeaders(texte) {
  const lignes = String(texte).replace(/^\uFEFF/, "").split(/\r?\n/);
  const regles = [];
  const defauts = [];
  let courante = null;
  lignes.forEach((brute, k) => {
    const n = k + 1;
    if (brute.length > MAX_LIGNE) defauts.push({ regle: "HD-2", ligne: n, msg: `ligne de ${brute.length} caractères, au-delà des 2 000 admis par ligne` });
    if (/^\s*$/.test(brute) || /^\s*#/.test(brute)) return;
    if (/^\s/.test(brute)) {
      const t = brute.trim();
      if (!courante) { defauts.push({ regle: "HD-1", ligne: n, msg: `en-tête « ${t.slice(0, 60)} » posé avant tout motif d'URL : il ne s'applique à aucune requête` }); return; }
      if (t.startsWith("!")) {
        const nom = t.slice(1).trim();
        if (!nom || /[:\s]/.test(nom)) { defauts.push({ regle: "HD-1", ligne: n, msg: `détachement « ${t.slice(0, 60)} » mal formé : « ! Nom-De-L-En-Tete » attendu` }); return; }
        courante.detaches.push({ nom: nom.toLowerCase(), ligne: n });
        return;
      }
      const i = t.indexOf(":");
      if (i <= 0) { defauts.push({ regle: "HD-1", ligne: n, msg: `ligne d'en-tête « ${t.slice(0, 60)} » sans la forme « nom: valeur »` }); return; }
      courante.attaches.push({ nom: t.slice(0, i).trim().toLowerCase(), valeur: t.slice(i + 1).trim(), ligne: n });
      return;
    }
    const motif = brute.trim();
    const probleme = verifierMotif(motif);
    courante = { motif, ligne: n, attaches: [], detaches: [], valide: !probleme };
    regles.push(courante);
    if (probleme) defauts.push({ regle: "HD-1", ligne: n, msg: `motif « ${motif.slice(0, 80)} » : ${probleme} ; la règle n'est pas sondée` });
  });
  if (regles.length > MAX_REGLES) defauts.push({ regle: "HD-2", ligne: regles[MAX_REGLES].ligne, msg: `${regles.length} règles, au-delà des 100 admises par fichier (la 101e commence ici)` });
  for (const r of regles) if (r.valide) r.regex = regexDe(r.motif);
  return { regles, defauts };
}

// ── Correspondance des motifs et sondes ────────────────────────────────────────────────────

const echapper = (s) => s.replace(/[.+?^${}()|[\]\\]/g, "\\$&");
const traduire = (s, dansHote) => echapper(s).replace(/\*/g, ".*").replace(/:[A-Za-z]\w*/g, dansHote ? "[^./]+" : "[^/]+");
const decouper = (motif) => {
  const reste = motif.slice(8);
  const j = reste.indexOf("/");
  return { hote: (j < 0 ? reste : reste.slice(0, j)).toLowerCase(), chemin: j < 0 ? "/" : reste.slice(j) };
};

function regexDe(motif) {
  if (/^https:\/\//i.test(motif)) {
    const { hote, chemin } = decouper(motif);
    return { absolu: true, re: new RegExp(`^${traduire(hote, true)}${traduire(chemin, false)}$`) };
  }
  return { absolu: false, re: new RegExp(`^${traduire(motif, false)}$`) };
}

function representant(motif) {
  const remplacer = (s) => s.replace(/:[A-Za-z]\w*/g, "x").replace(/\*/g, "x");
  if (/^https:\/\//i.test(motif)) {
    const { hote, chemin } = decouper(motif);
    return { hote: remplacer(hote), chemin: remplacer(chemin) };
  }
  return { hote: null, chemin: remplacer(motif) };
}

const correspond = (regle, sonde) => (regle.regex.absolu
  ? sonde.hote !== null && regle.regex.re.test(`${sonde.hote}${sonde.chemin}`)
  : regle.regex.re.test(sonde.chemin));

// Les en-têtes que le fichier applique à une sonde : attaches de toutes les règles qui
// correspondent (valeurs répétées jointes par une virgule, Set-Cookie gardé en liste), puis
// détachements de ces mêmes règles.
function enTetesPour(sonde, regles) {
  const enTetes = {};
  const appliquees = [];
  const valides = regles.filter((r) => r.valide && correspond(r, sonde));
  for (const r of valides) {
    appliquees.push(r.ligne);
    for (const a of r.attaches) {
      if (a.nom === "set-cookie") enTetes[a.nom] = [...(enTetes[a.nom] || []), a.valeur];
      else enTetes[a.nom] = enTetes[a.nom] === undefined ? a.valeur : `${enTetes[a.nom]}, ${a.valeur}`;
    }
  }
  for (const r of valides) for (const d of r.detaches) delete enTetes[d.nom];
  return { enTetes, appliquees };
}

export function jugerHeaders(texte, { fichier }) {
  const { regles, defauts } = lireHeaders(texte);
  const findings = defauts.map((d) => ({ sev: "majeur", regle: d.regle, msg: d.msg, where: `${fichier}:${d.ligne}`, source: PAGE_WORKERS }));
  const vues = new Map();
  const ajouter = (s, origine) => {
    const nom = s.hote ? `https://${s.hote}${s.chemin}` : s.chemin;
    if (!vues.has(nom)) vues.set(nom, { ...s, nom, origine });
  };
  ajouter({ hote: null, chemin: "/" }, "racine du site");
  for (const r of regles) if (r.valide) ajouter(representant(r.motif), `motif « ${r.motif} » (ligne ${r.ligne})`);
  const sondes = [];
  const groupes = new Map();
  for (const s of vues.values()) {
    const { enTetes, appliquees } = enTetesPour(s, regles);
    sondes.push({ sonde: s.nom, origine: s.origine, regles_appliquees: appliquees, en_tetes: enTetes });
    for (const f of jugerEnTetes(enTetes, { https: true })) {
      const cle = `${f.sev}|${f.regle}|${f.msg}|${f.where}`;
      if (!groupes.has(cle)) groupes.set(cle, { ...f, sondes: [] });
      groupes.get(cle).sondes.push(s.nom);
    }
  }
  for (const g of groupes.values()) {
    findings.push({ sev: g.sev, regle: g.regle, msg: g.msg, where: `${fichier} · ${g.sondes.length > 1 ? "sondes" : "sonde"} ${g.sondes.join(", ")} · ${g.where}`, sondes: g.sondes });
  }
  const parRegle = {};
  for (const f of findings) if (f.sev !== "info") parRegle[f.regle] = (parRegle[f.regle] || 0) + 1;
  return { findings, sondes, synthese: { regles: regles.length, regles_sondees: regles.filter((r) => r.valide).length, sondes: sondes.length, par_regle: parRegle } };
}

// ---- CLI -------------------------------------------------------------------------------------
const lanceEnDirect = process.argv[1]
  && fileURLToPath(import.meta.url).toLowerCase().split("\\").join("/")
     === path.resolve(process.argv[1]).toLowerCase().split("\\").join("/");
if (lanceEnDirect) {
  const args = process.argv.slice(2);
  const cible = args.find((a) => !a.startsWith("--"));
  const jsonOnly = args.includes("--json-only");
  const sortir = (verdict, code, findings, extra = {}) => {
    process.stdout.write(JSON.stringify({
      oracle: ORACLE, version: VERSION, artefact: cible || null, verdict,
      findings: findings.length ? findings : [{ sev: "info", regle: "—", msg: "aucun défaut détecté : HD-1, HD-2 et EX-1..EX-11 sur chaque sonde", where: cible }],
      ...extra, sources: SOURCES, non_juge: NON_JUGE,
    }, null, jsonOnly ? 0 : 2));
    process.exit(code);
  };
  if (!cible || !fs.existsSync(cible)) sortir("SKIP", 2, [{ sev: "info", regle: "—", msg: "cible introuvable", where: String(cible) }]);
  const fichier = fs.statSync(cible).isDirectory() ? path.join(cible, "_headers") : cible;
  if (!fs.existsSync(fichier)) sortir("SKIP", 2, [{ sev: "info", regle: "—", msg: "aucun fichier _headers dans ce dossier : rien à juger", where: cible }]);
  const affiche = path.relative(process.cwd(), fichier).split("\\").join("/") || fichier;
  const { findings, sondes, synthese } = jugerHeaders(fs.readFileSync(fichier, "utf8"), { fichier: affiche });
  const durs = findings.filter((f) => f.sev === "bloquant" || f.sev === "majeur");
  sortir(durs.length ? "FAIL" : "PASS", durs.length ? 1 : 0, findings, { sondes, synthese });
}
