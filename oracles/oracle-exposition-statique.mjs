// réseau : lit un fichier, ne contacte jamais Cloudflare). TF-1996, part websec.
// Il ne porte AUCUNE règle d'en-tête. Pour chaque requête sondée, il calcule les en-têtes que le
// fichier lui applique (règles dont le motif correspond, valeurs répétées jointes par une virgule,
// détachements « ! Nom »), puis les passe à `jugerEnTetes` d'oracle-exposition : les mêmes règles
// EX-1..EX-11 que sur une réponse capturée. Deux règles propres au fichier, tirées des pages lues
// le 28/10/2026 :
//   HD-1  syntaxe : en-tête posé hors de toute règle, ligne d'en-tête sans « nom: valeur »,
//         motif qui ne commence ni par / ni par https://, port dans une URL absolue, plus d'un
//         astérisque dans un motif ;
//   HD-2  limites : plus de 100 règles, ligne de plus de 2 000 caractères.
// Sondes : la racine « / », plus une URL représentative de chaque motif valide (« * » et
// « :nom » remplacés par « x »). Chaque constat EX dit les sondes qui le portent.
// Contrat : JSON {oracle, version, artefact, verdict, findings, sondes, synthese, sources, non_juge} · exit 0/1/2.
// Usage : node oracle-exposition-statique.mjs <fichier _headers | dossier qui le contient> [--json-only]
